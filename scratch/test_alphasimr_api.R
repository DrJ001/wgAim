suppressPackageStartupMessages(library(AlphaSimR))
set.seed(1)
fp <- runMacs2(nInd = 20, nChr = 2, segSites = 50, Ne = 50, genLen = 1.0)
SP <- SimParam$new(fp)
SP$addSnpChip(nSnpPerChr = 10)
pop <- newPop(fp, simParam = SP)
pop2 <- randCross(pop, nCrosses = 30, simParam = SP)
cat("nInd(pop2):", nInd(pop2), "\n")
g <- pullSnpGeno(pop2, simParam = SP)
cat("geno dim:", dim(g), "\n")
cat("geno range:", range(g), "\n")
cat("first 3 lines x 5 markers:\n")
print(g[1:3, 1:5])
m <- getSnpMap(simParam = SP)
cat("\nmap head:\n")
print(head(m))
cat("\nstr(m):\n")
str(m)
cat("\ntable(m$chr):\n")
print(table(m$chr))
cat("\nrange(m$site) per chr:\n")
print(tapply(m$site, m$chr, range))
