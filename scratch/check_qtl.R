library(qtl)
map <- sim.map(len=rep(50,2), n.mar=rep(5,2), eq.spac=TRUE, include.x=FALSE)
cr  <- sim.cross(map, n.ind=10, type="bc")
cat("class:", class(cr), "\n")
cat("geno[[1]] names:", names(cr$geno[[1]]), "\n")
cat("geno data dim:", dim(cr$geno[[1]]$data), "\n")
cat("geno data values (unique):", unique(as.vector(cr$geno[[1]]$data)), "\n")
cat("map values:", cr$geno[[1]]$map, "\n")
cat("pheno cols:", names(cr$pheno), "\n")
